import streamlit as st


# ============================================================
# CURRENCY SETUP
# ============================================================

def setup_currency():

    # --------------------------------------------------------
    # CURRENCY SELECTION
    # --------------------------------------------------------

    currency = st.sidebar.selectbox(
        "💱 Display Currency",
        [
            "INR (₹)",
            "USD ($)",
            "EUR (€)"
        ]
    )


    # --------------------------------------------------------
    # CURRENCY RATES
    # --------------------------------------------------------

    currency_rates = {
        "INR (₹)": 1.00,
        "USD ($)": 0.0117,
        "EUR (€)": 0.0100
    }


    # --------------------------------------------------------
    # CURRENCY SYMBOLS
    # --------------------------------------------------------

    currency_symbols = {
        "INR (₹)": "₹",
        "USD ($)": "$",
        "EUR (€)": "€"
    }


    # --------------------------------------------------------
    # SELECT CURRENT RATE
    # --------------------------------------------------------

    rate = currency_rates[currency]


    # --------------------------------------------------------
    # SELECT CURRENT SYMBOL
    # --------------------------------------------------------

    symbol = currency_symbols[currency]


    # --------------------------------------------------------
    # MONEY FORMATTER
    # --------------------------------------------------------

    def money(value):

        try:

            return (
                f"{symbol}"
                f"{float(value) * rate:,.0f}"
            )

        except (ValueError, TypeError):

            return f"{symbol}0"


    # --------------------------------------------------------
    # RETURN SETTINGS
    # --------------------------------------------------------

    return currency, rate, symbol, money
